import { SessionUsageStore } from "../../src/daemon/cache/session-usage-store.js";
import { GitService } from "../../src/segments/git.js";
import { hookData } from "../../test/helpers/drive-bar.js";
import { writeTranscript, makeRepo, scratchDir } from "./fixtures.js";
import path from "node:path";
const d = scratchDir("sp");
const t = path.join(d, "t.jsonl");
writeTranscript(t, "s1", d, 1700);
const store = new SessionUsageStore({ sweepIntervalMs: 0 });
let s = performance.now();
const r = await store.request("s1", t).usage(hookData(d, t));
console.log("fold", performance.now() - s, JSON.stringify(r).slice(0, 600));
s = performance.now();
const r2 = await store.request("s1", t).usage(hookData(d, t));
console.log("hit", performance.now() - s);
makeRepo(path.join(d, "repo"), { files: 200, commits: 5, modified: 5, untracked: 3 });
