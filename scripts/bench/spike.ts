const g = await new GitService().getGitInfo(path.join(d, "repo"), { showSha: true, showWorkingTree: true, showOperation: true, showTag: true, showCommittedAt: true, showStashCount: true, showUpstream: true, showRepoName: true, showRepoUrl: true });
console.log("git", performance.now() - s, JSON.stringify(g).slice(0, 500));
process.exit(0);
